#!/usr/bin/env python3
"""Generate a SWDownloader .blf that flashes OpenWrt onto the P298 (ASR1826s).

WHY THIS EXISTS
---------------
The goal was originally "patch mtd21 so U-Boot gives us a shell". That turns
out to be the wrong end of the problem. `archive/r291_openwrt_delivery/` has a
built kernel for this board, and OpenWrt produces a matching squashfs rootfs,
so the real task is to replace the vendor kernel and rootfs.

The vendor kernel and rootfs are NOT damaged. Every SHA-256 recorded in the
DTIM matches the corresponding partition byte-for-byte:

    mtd11/mtd12  u-boot a/b   digest present in DTIM
    mtd13/mtd14  kernel a/b   digest present in DTIM
    mtd15/mtd16  rootfs a/b   digest present in DTIM

The digest scheme is sha256 of the partition with trailing 0xFF stripped.
mtd21, the U-Boot environment, is not hashed at all -- which is why an env
write can never be rejected by DTIM verification, and why it is a poor thing
to spend a flashing campaign on.

WHAT THIS FLASHES
-----------------
One A/B slot, default slot A, which is the slot `mtd19` (asr_flag) reports as
active -- it contains the byte 'a' at offset 0xb8.

    mtd7   DTIM / TIM slot A    regenerated, Enable = 1
    mtd0   OBM                  Enable = 0, supplies the DKB only
    mtd13  kernel-a             Enable = 1
    mtd15  rootfs-a             Enable = 1

--slot ab adds mtd8/mtd14/mtd16 as well. That doubles the transfer for no
benefit when slot A is the live one, and if the flash goes wrong it destroys
the fallback too. Backups exist in findings/nand-dumps either way.

WHY mtd7 MUST BE WRITTEN
------------------------
The DTIM carries the kernel and rootfs digests. Replace either image without
replacing the DTIM and the hash check has nothing to match. mtd7 is therefore
enabled here, unlike in every mtd21-only .blf, where it sat at Enable = 0.

Whether the board enforces that check depends on Trusted mode: the [TIM_Corn-
figuration] here sets Trusted = 0 and Number_of_Keys = 0, matching the stock
unit. Writing mtd7 anyway is the safe choice -- it costs 256 KiB against a
7.3 MiB transfer.

SIZES -- THE INITRAMFS IMAGE DOES NOT FIT
-----------------------------------------
    squashfs-kernel  3,468,276 B   fits mtd13 (5,242,880)
    squashfs-rootfs  3,932,164 B   fits mtd15 (20,971,520)
    initramfs-kernel 7,221,772 B   does NOT fit mtd13

The initramfs image is 1.9 MB too large for the 5 MiB kernel partition. Using
it would mean repartitioning NAND, which means mtd23 and a new BBT -- a much
larger job than this. --check enforces the fit so that mistake cannot be made
by editing a .blf by hand.

TRANSFER COST
-------------
The board advertises `BufferSize is 0xF8`, 248 bytes, and the stock downloader
sends min(BufferSize, remaining). About 7.6 MB is therefore ~30,000 round
trips. Give the tool a generous -T; 180 s is not enough.

    sudo env LC_ALL=C LANG=C swdl_linux -D p298_openwrt_a.blf -S -T 1800 -N

USAGE
-----
    ./mk-openwrt-blf.py -o p298_openwrt_a.blf \\
        --kernel  ~/Downloads/openwrt/openwrt-fork/bin/targets/asr1802s/generic/openwrt-asr1802s-generic-asr1826s_p298-squashfs-kernel.bin \\
        --rootfs  ~/Downloads/openwrt/openwrt-fork/bin/targets/asr1802s/generic/openwrt-asr1802s-generic-asr1826s_p298-squashfs-rootfs.bin \\
        --validate

    ./mk-openwrt-blf.py --check --kernel K --rootfs R     # sizes only
    ./mk-openwrt-blf.py --describe                        # the partition table
"""

import argparse
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SWD = REPO / "flashing_tools" / "p298-swd"
ORACLE = REPO / "flashing_tools" / "Marvell_SWDownloader_v4.8.8.2" / \
    "Utilities" / "MakeDownloadPackage" / "MakeDownloadPackage"
DKB_P298 = "mtd0.bin"           # the board's own OBM, 262144 B
DKB_AIR720 = "Nezha_loader_MIFI_V5_SPI_NAND_Release.bin"   # 79924 B

# mtd, flash entry address, erase size, partition number
DTIM = {  "a": (7, 0x01000000), "b": (8, 0x01400000) }
KERNEL = {"a": (13, 0x02100000), "b": (14, 0x02600000) }
ROOTFS = {  "a": (15, 0x02B00000), "b": (16, 0x03F00000) }

ERASE_DTIM = 0x40000
ERASE_KERNEL = 0x500000        # 5120 KiB
ERASE_ROOTFS = 0x1400000       # 20480 KiB
ERASE_UBOOT = 0xC0000         # 768 KiB
ERASE_FLAG = 0xC0000          # mtd19, 768 KiB
UBOOT = {"a": (11, 0x01F80000), "b": (12, 0x02040000)}
FLAG_PART, FLAG_ADDR = 19, 0x05F00000

KERNEL_LOAD = 0x80008000
UBOOT_LOAD = 0x00800000       # per README-R291.md, "uImage-r291 load 0x80008000"
ROOTFS_LOAD = 0x00000000

IMG_TIMH = 0x54494D48
IMG_OBMI = 0x4F424D49
IMG_RAW = 0x52444348
IMG_END = 0xFFFFFFFF

HEADER = """; =====================================================================
; P298 (ASR1826s) OpenWrt flash -- generated by tools/mk-openwrt-blf.py
; ---------------------------------------------------------------------
; Replaces the vendor kernel and rootfs in slot {slots} and rewrites the DTIM
; so its SHA-256 digests match the new images.
;
; Slots      : {slots}   (mtd19 asr_flag reports 'a' active)
; Kernel     : {kname}  ({ksize:,} B) -> mtd{kpart} @ {kaddr:#010x}
; Rootfs     : {rname}  ({rsize:,} B) -> mtd{rpart} @ {raddr:#010x}
; DTIM       : regenerated -> mtd{dpart}
; OBM        : {dkbname} (DKB only, Enable = 0, not written)
;
; Flash     : SPI-NAND, block size 0x20000
; Platform  : PXA1826 -> NEZHA3
; Trusted   : 0, Number_of_Keys = 0 (matches the stock unit)
;
; Run:
;   sudo env LC_ALL=C LANG=C swdl_linux -D {out} -S -T 1800 -N
;
; The board advertises BufferSize 0xF8 = 248 B, so the payload is roughly
; 30,000 round trips. -T 180 s is not enough. -S exits by itself when done.
;
; DO NOT interrupt this run. A download that is cut short leaves the FBF in
; SRAM unexecuted and the board resets back to the old firmware.
;
; Verified on 2026-10-16 that the vendor kernel and rootfs are NOT corrupt:
; every digest recorded in the stock DTIM matches its partition. This .blf is
; a replacement, not a repair.
; =====================================================================
"""

FMT = "{slots} {kname} {ksize:,} {kpart} {kaddr:#010x} {rname} {rsize:,} " \
      "{rpart} {raddr:#010x} {dpart} {dkbname} {out}"


def image(idx, enable, tim_included, image_id, next_id, path, addr, load,
          erase, part, name):
    return f"""{idx}_Image_Enable = {enable}
{idx}_Image_Tim_Included = {tim_included}
{idx}_Image_Image_ID = 0x{image_id:08X}
{idx}_Image_Next_Image_ID = 0x{next_id:08X}
{idx}_Image_Path = {path}
{idx}_Image_Flash_Entry_Address = 0x{addr:08X}
{idx}_Image_Load_Address = 0x{load:08X}
{idx}_Image_Type = RAW
{idx}_Image_ID_Name = {name}
{idx}_Image_Erase_Size = 0x{erase:X}
{idx}_Image_Partition_Number = {part}
{idx}_Image_Size_To_CRC_in_bytes = 0

"""


def describe() -> None:
    print("P298 OpenWrt flash targets")
    print()
    print("slot  DTIM  kernel  rootfs")
    for s in ("a", "b"):
        d, da = DTIM[s]
        k, ka = KERNEL[s]
        r, ra = ROOTFS[s]
        print(f"  {s}    mtd{d}   mtd{k:<2}   mtd{r}")
    print()
    print(f"  DTIM   erase {ERASE_DTIM:#x}   ({ERASE_DTIM//1024} KiB)")
    print(f"  kernel erase {ERASE_KERNEL:#x}   ({ERASE_KERNEL//1024} KiB)")
    print(f"  rootfs erase {ERASE_ROOTFS:#x}   ({ERASE_ROOTFS//1024} KiB)")
    print()
    print("digest scheme the DTIM uses:")
    print("  sha256(partition with trailing 0xFF stripped)")


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.splitlines()[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="see the module docstring for the flash layout and rationale")
    ap.add_argument("-o", "--output")
    ap.add_argument("--kernel")
    ap.add_argument("--rootfs")
    ap.add_argument("--slot", default="a", choices=["a", "b", "ab"])
    ap.add_argument("--dkb", default="air720", choices=["air720", "p298"],
                    help="which file supplies the DKB (default air720, "
                         "79,924 B, the one proven to work on this board)")
    ap.add_argument("--uboot", help="u-boot image for the slot, from the\n                        verified dump. Optional: the stock u-boot boots a new\n                        uImage kernel fine. Write it to make the slot\n                        self-consistent, or to rule out a corrupt live copy.")
    ap.add_argument("--slot-flag", help="asr_flag image selecting this slot, e.g.\n                        mtd19.slotb.bin. Always written LAST so an interrupted\n                        run leaves the previous slot active.")
    ap.add_argument("--write-dtim", action="store_true",
                    help="also write the regenerated DTIM. Discards 2,364 bytes of\n                         DDR/PP settings and carries no image digests at\n                         Trusted = 0. There to test, not to use.")
    ap.add_argument("--check", action="store_true",
                    help="only verify the images fit their partitions")
    ap.add_argument("--validate", action="store_true",
                    help="run the vendor MakeDownloadPackage oracle")
    ap.add_argument("--describe", action="store_true")
    args = ap.parse_args()

    if args.describe:
        describe()
        return 0
    if not (args.kernel and args.rootfs):
        ap.error("--kernel and --rootfs are required (or use --describe)")
    if not args.check and not args.output:
        ap.error("-o/--output is required unless --check")

    kpath, rpath = Path(args.kernel), Path(args.rootfs)
    for p in (kpath, rpath):
        if not p.exists():
            print(f"error: {p} not found", file=sys.stderr)
            return 1

    ksize, rsize = kpath.stat().st_size, rpath.stat().st_size
    slots = list("ab") if args.slot == "ab" else [args.slot]

    # Size gate. The initramfs image is 1.9 MB too big for mtd13 and this is
    # the single easiest way to turn a recovery into a dead board.
    bad = False
    for s in slots:
        _, _ = KERNEL[s]
        if ksize > ERASE_KERNEL:
            print(f"error: kernel is {ksize:,} B but mtd{KERNEL[s][0]} holds "
                  f"{ERASE_KERNEL:,} B -- it will not fit.", file=sys.stderr)
            bad = True
        if rsize > ERASE_ROOTFS:
            print(f"error: rootfs is {rsize:,} B but mtd{ROOTFS[s][0]} holds "
                  f"{ERASE_ROOTFS:,} B -- it will not fit.", file=sys.stderr)
            bad = True
    if bad:
        print("\nThe initramfs kernel (7,221,772 B) does not fit a 5 MiB "
              "kernel\npartition. Repartitioning means mtd23 and a new BBT, "
              "which is a\ndifferent job. Use the squashfs pair.",
              file=sys.stderr)
        return 1

    kpart, kaddr = KERNEL[slots[0]]
    rpart, raddr = ROOTFS[slots[0]]
    dpart, _ = DTIM[slots[0]]
    total = ksize + rsize + ERASE_DTIM * len(slots)
    print(f"kernel {ksize:,} B -> mtd{kpart} @ {kaddr:#010x}")
    print(f"rootfs {rsize:,} B -> mtd{rpart} @ {raddr:#010x}")
    print(f"DTIM   regenerated -> mtd{dpart}")
    print(f"slots  {args.slot}   total payload ~{total:,} B")
    print(f"at the board's advertised 248 B buffer that is roughly "
          f"{total // 248:,} round trips")

    if args.check:
        print("fits.")
        return 0

    dkb_name = DKB_P298 if args.dkb == "p298" else DKB_AIR720
    dkb_erase = 0x40000 if args.dkb == "p298" else 0x20000

    body = []
    idx = 0
    # Build the chain: TIMH -> OBMI -> [kernel, rootfs per slot] -> END
    # Order matters, twice over.
    #
    # The chain must be TIMH -> OBMI -> payloads -> end, because the DKB is
    # located through Next_Image_ID. Put the OBMI anywhere else and
    # MakeDownloadPackage fails with "OBMImage is NULL in prepareDKB list".
    #
    # Beyond that, the ORDER OF THE WRITES IS THE SAFETY PROPERTY: the mtd19
    # slot switch is always the last image. The tool writes in chain order, so
    # if the transfer is cut short -- power loss, cable, timeout -- the switch
    # has not happened yet and the board still boots slot A, untouched. The
    # rollback is the same 272 bytes written the other way.
    #
    # The DTIM is supplied as the TIMH source but NOT written, and that is
    # deliberate. MakeDownloadPackage regenerates it as 152 bytes containing no
    # image digests at all (Trusted = 0), while the stock mtd8 is 2,516 bytes of
    # populated DDR and PP settings. Writing the regenerated one would discard
    # all of it. --write-dtim exists to test that conclusion, not to use it.
    plan = []
    for s in slots:
        d, da = DTIM[s]
        k, ka = KERNEL[s]
        r, ra = ROOTFS[s]
        u, ua = UBOOT[s]
        plan.append(("TIMH", da, ERASE_DTIM, d, True, 0, f"mtd{d}.bin"))
        plan.append(("OBMI", 0x00000000, dkb_erase, 0, True, 0, dkb_name))
        if args.uboot:
            plan.append(("UBOOT", ua, ERASE_UBOOT, u, False, 0,
                         Path(args.uboot).name))
        plan.append(("KERN", ka, ERASE_KERNEL, k, False, 0, kpath.name))
        plan.append(("ROOT", ra, ERASE_ROOTFS, r, False, 0, rpath.name))
        if args.slot_flag:
            plan.append(("FLAG", FLAG_ADDR, ERASE_FLAG, FLAG_PART, False, 0,
                         Path(args.slot_flag).name))
    ids = {"TIMH": IMG_TIMH, "OBMI": IMG_OBMI, "KERN": IMG_RAW,
           "ROOT": IMG_RAW, "UBOOT": IMG_RAW, "FLAG": IMG_RAW}
    names = {"TIMH": "TIMH", "OBMI": "OBMI", "KERN": "KERN0",
             "ROOT": "ROOT0", "UBOOT": "UBOT0", "FLAG": "ASRF0"}

    for i, (kind, addr, erase, part, tim_inc, _x, path) in enumerate(plan):
        n = i + 1
        nxt = ids[plan[i + 1][0]] if i + 1 < len(plan) else IMG_END
        if kind == "TIMH":
            load = 0xD1101000
        elif kind == "OBMI":
            load = 0x01C00000
        elif kind == "KERN":
            load = KERNEL_LOAD
        elif kind == "UBOOT":
            load = UBOOT_LOAD
        elif kind == "FLAG":
            load = ROOTFS_LOAD
        else:
            load = ROOTFS_LOAD
        # Enable = 0 means "supply this file, do not write it to flash".
        #
        # OBMI is always 0: the DKB is uploaded into BootROM SRAM and nothing
        # else. Writing it would rewrite the OBM.
        #
        # TIMH is 0 by default and only 1 under --write-dtim. The regenerated
        # DTIM is 152 bytes with no image digests at Trusted = 0, while the
        # stock mtd8 carries 2,516 bytes of populated DDR and PP settings the
        # OBM needs. Writing the regenerated one would discard all of it, so
        # the safe default is to leave the DTIM alone entirely.
        if kind == "OBMI":
            en = 0
        elif kind == "TIMH":
            en = 1 if args.write_dtim else 0
        else:
            en = 1
        body.append(image(n, en, 1 if tim_inc else 0, ids[kind], nxt, path,
                          addr, load, erase, part, names[kind]))

    out = Path(args.output)
    head = HEADER.format(
        slots=args.slot, kname=kpath.name, ksize=ksize, kpart=kpart, kaddr=kaddr,
        rname=rpath.name, rsize=rsize, rpart=rpart, raddr=raddr, dpart=dpart,
        dkbname=dkb_name, out=out.name)

    text = head + """
[TIM_Configuration]
Number_of_Images = %d
Number_of_Keys = 0
Boot_Flash_Signature = 0x5350490A
Processor_Type = PXA1826
OEM_UniqueID = 0x21796B53
Issue_Date = 0x20141006
Version = 0x00030400
Trusted = 0
ProductionMode = 0

[Flash_Properties]
Flash_Block_Size = 0x20000
Flash_Family = SPI-NAND
Erase_All_Flash = 0
Reset_BBT = 0

[Image_List]
""" % len(plan) + "".join(body)

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"\nwrote {out}")

    if args.validate:
        if not ORACLE.exists():
            print("oracle not found:", ORACLE, file=sys.stderr)
            return 1
        # NEVER run the oracle in p298-swd: it rewrites image files in place.
        with tempfile.TemporaryDirectory() as td:
            work = Path(td)
            for name in ([args.uboot and Path(args.uboot).name] +
                         [args.slot_flag and Path(args.slot_flag).name] +
                         [kpath.name, rpath.name, dkb_name] +
                         [f"mtd{DTIM[s][0]}.bin" for s in slots]):
                src = SWD / name
                if not src.exists():
                    print(f"  note: {name} not in {SWD}, skipping copy")
                    continue
                shutil.copy2(src, work / name)
            shutil.copy2(ORACLE, work / ORACLE.name)
            shutil.copy2(out, work / out.name)
            r = subprocess.run(
                ["env", "LC_ALL=C", "LANG=C", str(work / ORACLE.name),
                 "-r", str(work / out.name), "-o", str(work / "pkg.zip")],
                cwd=work, capture_output=True, text=True)
            tail = (r.stdout + r.stderr).strip().splitlines()[-4:]
            print("\noracle:", "\n  ".join(tail))
            ok = "Make Download Package successfully" in r.stdout + r.stderr
            print("oracle result:", "PASS" if ok else "FAIL")
            return 0 if ok else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())